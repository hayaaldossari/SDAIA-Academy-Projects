from google import genai
import faiss
import numpy as np
import json

client = genai.Client(api_key="API_KEY_HERE")

# Load the FAISS database

index = faiss.read_index(
    "places_faiss.index"
)

print("Number of vectors:", index.ntotal)

# Load chunk metadata

with open("chunks_metadata.json", "r", encoding="utf-8") as file:

    all_chunks = json.load(file)

print("Number of chunks:", len(all_chunks))

# Define the retrieval function

def ask_question(question, top_k=3):

    print("\n================================")
    print("QUESTION")
    print("================================")
    print(question)

    # Convert question into embedding

    query_result = client.models.embed_content(
        model="gemini-embedding-2",
        contents=question
    )

    query_vector = np.array(
        [query_result.embeddings[0].values],
        dtype="float32"
    )

    # Normalize query vector

    faiss.normalize_L2(query_vector)

    # Search the vector database

    scores, indices = index.search(
        query_vector,
        top_k
    )

    print("\n================================")
    print("TOP RELEVANT CHUNKS")
    print("================================")

    retrieved_chunks = []

    for rank, (score, idx) in enumerate(
        zip(scores[0], indices[0]), 1
    ):

        chunk = all_chunks[idx]

        print(f"\n--- Result {rank} ---")
        print(f"Cosine Similarity: {score:.4f}")
        print(f"Source: {chunk['file_name']}")
        print("Text:")
        print(chunk["text"])

        retrieved_chunks.append(chunk["text"])

    # Combine retrieved chunks

    context = "\n\n".join(
        retrieved_chunks
    )

    # Generate answer using context

    prompt = f"""
You are a question-answering assistant.

Answer the question using ONLY the information provided in the context.

Context:
{context}

Question:
{question}

If the answer can be found or reasonably determined from the context,
give the answer directly and briefly.

If the context truly does not contain enough information to answer,
say:
"I don't have enough information to answer this."
"""

    response = client.models.generate_content(
        model="gemini-3.1-flash-lite",
        contents=prompt
    )

    print("\n================================")
    print("ANSWER")
    print("================================")

    print(response.text)

    return response.text

# Test a city question

answer = ask_question(
    "What is AlUla famous for?"
)

# Test a project question

